def paper_tiles(w, h):
    """四块重叠局部。长条图沿长轴分段，普通图按象限分块。"""
    if w >= 2.4 * h:
        cols, rows = 4, 1
    elif h >= 2.4 * w:
        cols, rows = 1, 4
    else:
        cols, rows = 2, 2
    pad_x, pad_y = max(1, round(w / cols * 0.08)), max(1, round(h / rows * 0.08))
    boxes = {}
    for n in range(4):
        x, y = n % cols, n // cols
        boxes[f"Z{n+1}"] = [(max(0, w*x//cols-pad_x), max(0, h*y//rows-pad_y),
                              min(w, w*(x+1)//cols+pad_x), min(h, h*(y+1)//rows+pad_y))]
    return boxes
